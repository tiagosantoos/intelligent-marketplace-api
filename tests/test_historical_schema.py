from io import StringIO

import pytest
from alembic import command
from alembic.config import Config

from intelligent_marketplace.infrastructure.models.historical import metadata


def test_nine_source_tables_are_isolated_in_historical_schema():
    assert {table.name for table in metadata.tables.values()} == {
        "customers", "orders", "order_items", "order_payments", "order_reviews",
        "products", "sellers", "geolocation", "product_category_name_translation",
    }
    assert all(table.schema == "historical" for table in metadata.tables.values())


@pytest.mark.parametrize(
    ("table", "columns"),
    [
        ("order_reviews", ["review_id", "order_id"]),
        ("order_items", ["order_id", "order_item_id"]),
        ("order_payments", ["order_id", "payment_sequential"]),
    ],
)
def test_source_composite_keys_do_not_discard_distinct_records(table, columns):
    assert list(metadata.tables[f"historical.{table}"].primary_key.columns.keys()) == columns


def test_geolocation_preserves_repeated_prefixes():
    table = metadata.tables["historical.geolocation"]
    assert list(table.primary_key.columns.keys()) == ["geolocation_id"]
    assert table.c.geolocation_id.identity is not None
    assert not table.c.geolocation_zip_code_prefix.unique


def test_optional_dates_and_product_attributes_remain_nullable():
    orders = metadata.tables["historical.orders"]
    for name in ("order_approved_at", "order_delivered_carrier_date", "order_delivered_customer_date"):
        assert orders.c[name].nullable
        assert orders.c[name].type.timezone is False
    products = metadata.tables["historical.products"]
    assert products.c.product_category_name.nullable
    assert products.c.product_weight_g.nullable
    assert "product_name_lenght" in products.c


def test_migration_generates_postgres_sql_without_database():
    output = StringIO()
    command.upgrade(Config("alembic.ini", output_buffer=output), "head", sql=True)
    sql = output.getvalue()
    assert "CREATE SCHEMA historical" in sql
    assert sql.count("CREATE TABLE historical.") == 9
    assert "GENERATED BY DEFAULT AS IDENTITY" in sql
    for table in metadata.tables.values():
        assert f"CREATE TABLE historical.{table.name}" in sql
        for column in table.columns:
            assert column.name in sql
        for index in table.indexes:
            assert index.name in sql
    assert "PRIMARY KEY (review_id, order_id)" in sql


def test_downgrade_generates_explicit_drops_without_cascade():
    output = StringIO()
    command.downgrade(Config("alembic.ini", output_buffer=output), "0001:base", sql=True)
    sql = output.getvalue()
    assert sql.count("DROP TABLE historical.") == 9
    assert "DROP SCHEMA historical" in sql
    assert "CASCADE" not in sql
